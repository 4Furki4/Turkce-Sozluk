import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import postgres from "postgres";
import { drizzle } from "drizzle-orm/postgres-js";
import { ciEnvironment } from "../scripts/ci/env.mjs";
import { getSearchGaps, reviewSearchGap } from "../src/server/search-gaps";
import { recordSearchOutcome } from "../src/server/search-outcomes";
import { searchOutcomeInputSchema, type SearchOutcomeInput } from "../src/lib/search-outcome-schema";
import { cleanupSearchOutcomeEvents } from "./helpers/search-outcomes";
import en from "../messages/en.json";
import tr from "../messages/tr.json";

test.use({ timezoneId: "America/Los_Angeles" });
const DAY = 86_400_000;

test("SQL grouping, source denominators, retention boundaries, current matches and triage remain independent", async () => {
  const sql = postgres(ciEnvironment().DATABASE_URL, { max: 1 });
  await sql`SELECT pg_advisory_lock(20261015, 4)`;
  const db = drizzle(sql);
  const events = new Set<string>();
  const words: number[] = [];
  const prefix = "gap " + randomUUID().replace(/[^a-z]/g, "") + " ";
  const actorId = randomUUID();
  const now = new Date("2096-06-03T12:00:00Z");
  const selection = { range: "custom" as const, start: "2096-06-01", end: "2096-06-02" };
  const a = prefix + "ığdır";
  const b = prefix + "eşit";
  const recent = prefix + "son";
  const seed = async (query: string, at: string | Date, outcome: SearchOutcomeInput["outcome"] = "no_result", source: "online" | "offline" = "online") => {
    const event = searchOutcomeInputSchema.parse({ query, eventId: randomUUID(), locale: "tr", entryPoint: "search", source, outcome, resultCount: outcome === "resolved" ? 1 : 0 });
    events.add(event.eventId);
    await recordSearchOutcome(db as never, event, new Date(at));
  };
  try {
    await sql`SET TIME ZONE 'Pacific/Auckland'`;
    await sql`INSERT INTO users (id, email, role) VALUES (${actorId}, ${`${actorId}@example.invalid`}, 'admin')`;
    await seed(prefix + "IĞDIR", "2096-06-01T00:00:00Z");
    await seed(a, "2096-06-02T08:00:00Z");
    await seed(b, "2096-06-01T00:00:00Z");
    await seed(b, "2096-06-02T08:00:00Z");
    await seed(recent, "2096-06-02T23:59:59.999Z");
    await seed(prefix + "k_tap", "2096-06-02T08:00:00Z", "no_result", "offline");
    await seed(recent, "2096-06-02T08:00:00Z", "resolved");
    await seed(prefix + "hata", "2096-06-02T08:00:00Z", "error");
    await seed(prefix + "iptal", "2096-06-02T08:00:00Z", "cancelled");
    await seed(prefix + "yeni", "2096-06-02T08:00:00Z", "superseded");
    await seed(prefix + "önce", "2096-05-31T23:59:59.999Z");
    await seed(prefix + "sonra", "2096-06-03T00:00:00Z");
    const result = await getSearchGaps(db as never, { selection, q: prefix, status: "all" }, now);
    expect(result.summary).toMatchObject({ reported: 10, completed: 7, noResult: 6, errors: 1, noResultRate: 6 / 7 });
    expect(result.total).toBe(4);
    const beyondLast = await getSearchGaps(db as never, { selection, q: prefix, page: 999, pageSize: 5 }, now);
    expect(beyondLast).toMatchObject({ page: 1, total: 4 });
    expect(beyondLast.items).toHaveLength(4);
    expect(result.items.slice(0, 2).map(row => row.query)).toEqual([b, a].sort());
    expect(result.items.find(row => row.query === a)).toMatchObject({ frequency: 2, firstSeen: new Date("2096-06-01T00:00:00Z"), lastSeen: new Date("2096-06-02T08:00:00Z"), currentWord: null });
    expect(result.items.find(row => row.query === a)?.daily).toEqual([{ date: "2096-06-01", count: 1 }, { date: "2096-06-02", count: 1 }]);
    expect((await getSearchGaps(db as never, { selection, source: "offline" }, now)).summary).toMatchObject({ completed: 1, noResult: 1, noResultRate: 1 });
    expect((await getSearchGaps(db as never, { selection, kind: "word" }, now)).summary.noResultRate).toBe(5 / 6);
    expect((await getSearchGaps(db as never, { selection, q: prefix, sort: "recent" }, now)).items[0]?.query).toBe(recent);
    await seed(prefix + "İZ", "2096-06-02T09:00:00Z");
    await seed(prefix + "IZ", "2096-06-02T09:00:00Z");
    expect((await getSearchGaps(db as never, { selection, q: prefix + "iz" }, now)).items.map(row => row.query)).toEqual([prefix + "iz"]);
    expect((await getSearchGaps(db as never, { selection, q: prefix + "ız" }, now)).items.map(row => row.query)).toEqual([prefix + "ız"]);
    const quiet = await getSearchGaps(db as never, { selection: { range: "custom", start: "2096-05-01", end: "2096-05-01" } }, now);
    expect(quiet.summary).toMatchObject({ reported: 0, completed: 0, noResultRate: null });
    await seed(prefix + "yerel hata", "2096-06-02T08:00:00Z", "error", "offline");
    const operational = await getSearchGaps(db as never, { selection, source: "offline", kind: "word" }, now);
    expect(operational.summary).toMatchObject({ reported: 1, completed: 0, noResult: 0, errors: 1, noResultRate: null });
    expect(operational.total).toBe(0);
    const [added] = await sql`INSERT INTO words (name, variant) VALUES (${a}, 0) RETURNING id`;
    words.push(added.id);
    const after = await getSearchGaps(db as never, { selection, q: a }, now);
    expect(after.items[0]).toMatchObject({ frequency: 2, currentWord: { id: added.id, name: a } });
    await reviewSearchGap(db as never, { query: a, status: "linked", targetType: "word", targetId: added.id }, actorId, now);
    expect((await getSearchGaps(db as never, { selection, q: a }, now)).total).toBe(0);
    expect((await getSearchGaps(db as never, { selection, q: a, status: "linked" }, now)).items[0]).toMatchObject({ status: "linked", targetId: added.id, linkedWordName: a });
    await expect(reviewSearchGap(db as never, { query: b, status: "linked", targetType: "request", targetId: 2147483647 }, actorId, now)).rejects.toMatchObject({ code: "NOT_FOUND" });
    await reviewSearchGap(db as never, { query: a, status: "open" }, actorId, now);
    expect((await getSearchGaps(db as never, { selection, q: a }, now)).total).toBe(1);
    await sql`INSERT INTO search_gap_reviews (query, status, updated_at) VALUES (${recent}, 'dismissed', ${new Date(now.getTime() - 91 * DAY).toISOString()})`;
    expect((await getSearchGaps(db as never, { selection, q: recent }, now)).items[0]?.status).toBe("open");
    const cutoff = new Date(now.getTime() - 90 * DAY);
    await seed(prefix + "saklanan", cutoff);
    await seed(prefix + "saklanan", new Date(cutoff.getTime() - 1));
    const end = cutoff.toISOString().slice(0, 10);
    const start = new Date(Date.parse(end) - 89 * DAY).toISOString().slice(0, 10);
    const retained = await getSearchGaps(db as never, { selection: { range: "custom", start, end }, q: prefix }, now);
    expect(retained.coverage).toMatchObject({ truncated: true, retainedFrom: cutoff });
    expect(retained.items[0]?.frequency).toBe(1);
    expect(retained.daily[0]).toMatchObject({ noResult: null, errors: null });
    await sql`DELETE FROM users WHERE id = ${actorId}`;
    // The no-result query and its review state are not owned by a reader account.
    expect((await getSearchGaps(db as never, { selection, q: b }, now)).total).toBe(1);
  } finally {
    await sql`DELETE FROM search_gap_reviews WHERE query LIKE ${prefix + "%"}`;
    await cleanupSearchOutcomeEvents(sql, events);
    if (words.length) await sql`DELETE FROM words WHERE id IN ${sql(words)}`;
    await sql`DELETE FROM users WHERE id = ${actorId}`;
    await sql`SELECT pg_advisory_unlock(20261015, 4)`;
    await sql.end({ timeout: 5 });
  }
});

for (const locale of ["tr", "en"] as const) {
  test(`${locale}: gaps support current rechecks, URL filters, triage and existing workflows`, async ({ page }, testInfo) => {
    test.setTimeout(90_000);
    const sql = postgres(ciEnvironment().DATABASE_URL, { max: 1 });
    const db = drizzle(sql);
    const copy = (locale === "tr" ? tr : en).Dashboard.searchGaps;
    const errors: string[] = [];
    const events = new Set<string>();
    const prefix = "sözlük " + randomUUID().replace(/[^a-z]/g, "") + " ";
    const term = prefix + "aranan";
    const longTerm = prefix + "uzun".repeat(15);
    const wordIds: number[] = [];
    let actorId: string | undefined;
    const path = locale === "tr" ? "/tr/panel/sonucsuz-aramalar" : "/en/dashboard/search-gaps";
    const now = new Date();
    const end = new Date(now.getTime() - 2 * DAY).toISOString().slice(0, 10);
    const start = new Date(now.getTime() - 3 * DAY).toISOString().slice(0, 10);
    const reportAt = new Date(`${start}T12:00:00Z`);
    const url = `${path}?range=custom&start=${start}&end=${end}&q=${encodeURIComponent(prefix)}`;
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => { if (/width\(-1\)|height\(-1\)|MISSING_MESSAGE|FORMATTING_ERROR/.test(message.text())) errors.push(message.text()); });
    await page.route(/^https:\/\//, route => route.abort());
    await page.context().setExtraHTTPHeaders({ "x-forwarded-for": `10.63.${Math.floor(Math.random() * 255)}.${Math.floor(Math.random() * 255)}` });
    await page.emulateMedia({ reducedMotion: "reduce" });
    const choose = async (label: string, value: string) => {
      const trigger = page.getByRole("button", { name: label, exact: true });
      await trigger.scrollIntoViewIfNeeded();
      if (testInfo.project.name === "mobile") await trigger.tap(); else await trigger.click();
      await page.getByRole("option", { name: value, exact: true }).click();
    };
    try {
      const identity = "gaps_" + randomUUID().replaceAll("-", "");
      const email = `${identity}@example.invalid`;
      const password = "ci-only-search-gaps-password";
      const signup = await page.request.post("/api/auth/sign-up/email", { headers: { origin: "http://localhost:3100" }, data: { email, name: "Gap Reviewer", username: identity, password } });
      expect(signup.ok(), await signup.text()).toBe(true);
      actorId = (await signup.json()).user.id;
      await sql`UPDATE users SET role = 'admin' WHERE id = ${actorId!}`;
      await page.request.post("/api/auth/sign-out", { headers: { origin: "http://localhost:3100" } });
      expect((await page.request.post("/api/auth/sign-in/email", { headers: { origin: "http://localhost:3100" }, data: { email, password } })).ok()).toBe(true);
      for (const [query, n] of [[term, 3], [longTerm, 2], ...Array.from({ length: 10 }, (_, index) => [prefix + "terim " + String.fromCharCode(97 + index), 1])] as Array<[string, number]>) {
        for (let i = 0; i < n; i++) {
          const id = randomUUID(); events.add(id);
          await recordSearchOutcome(db as never, { eventId: id, query, locale, entryPoint: "search", source: "online", outcome: "no_result", resultCount: 0 }, reportAt);
        }
      }
      await page.goto(url);
      await expect(page.getByRole("heading", { name: copy.title, exact: true })).toBeVisible();
      const items = page.getByTestId("search-gap-item");
      await expect(items).toHaveCount(10);
      await expect(items.first().getByRole("heading", { name: term, exact: true })).toBeVisible();
      const sizes = await page.locator('form').filter({ has: page.getByRole("textbox", { name: copy.filters.query, exact: true }) }).locator('[data-slot="input-wrapper"], [data-slot="trigger"], button[type="submit"]').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().height));
      expect(sizes).toHaveLength(6);
      expect(sizes.every(height => Math.abs(height - 40) < 1)).toBe(true);
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({ path: testInfo.outputPath("search-gaps-list.png"), fullPage: true, scale: "css", animations: "disabled" });
      await page.screenshot({ path: testInfo.outputPath("search-gaps-list-viewport.png"), scale: "css", animations: "disabled" });
      await page.getByRole("button", { name: copy.pagination.next, exact: true }).click();
      await expect(page).toHaveURL(/page=2/);
      await expect(items).toHaveCount(2);
      await page.goBack();
      await expect(items).toHaveCount(10);
      await items.first().getByRole("button", { name: copy.actions.inspect, exact: true }).click();
      const createLink = items.first().getByRole("link", { name: copy.actions.createWord, exact: true });
      await expect(createLink).toHaveAttribute("href", new RegExp(locale === "tr" ? "/tr/panel/kelime-ekle\\?name=" : "/en/dashboard/create-word\\?name="));
      await createLink.click();
      const nameInput = page.locator('input[name="name"]');
      await expect(nameInput).toHaveValue(term);
      await page.goBack();
      await items.first().getByRole("button", { name: copy.actions.inspect, exact: true }).click();
      await items.first().getByRole("link", { name: copy.actions.correctSpelling, exact: true }).click();
      await expect(page).toHaveURL(new RegExp(locale === "tr" ? "/tr/panel/yazim-yanlislari/yeni" : "/en/dashboard/misspellings/new"));
      await expect(page.getByRole("heading", { name: (locale === "tr" ? tr : en).TaskPage.newMisspelling, exact: true })).toBeVisible();
      await expect(page.getByLabel((locale === "tr" ? tr : en).Dashboard.Misspellings.incorrectSpellingLabel, { exact: true })).toHaveValue(term);
      await page.goto(url);
      const [word] = await sql`INSERT INTO words (name, variant) VALUES (${term}, 0) RETURNING id`;
      wordIds.push(word.id);
      await page.getByRole("button", { name: copy.actions.refresh, exact: true }).click();
      await expect(items.first().getByText(copy.current.word, { exact: false })).toBeVisible();
      await expect(items.first().getByRole("link", { name: term, exact: true })).toBeVisible();
      await items.first().getByRole("button", { name: copy.actions.inspect, exact: true }).click();
      await choose(copy.review.status, copy.statuses.reviewed);
      await items.first().getByRole("button", { name: copy.review.save, exact: true }).click();
      await expect(items.filter({ has: page.getByRole("heading", { name: term, exact: true }) })).toHaveCount(0);
      await choose(copy.filters.status, copy.statuses.reviewed);
      await page.getByRole("button", { name: copy.filters.apply, exact: true }).click();
      await expect(page).toHaveURL(/status=reviewed/);
      await expect(items).toHaveCount(1);
      await page.reload();
      await expect(items).toHaveCount(1);
      await items.first().getByRole("button", { name: copy.actions.inspect, exact: true }).click();
      await choose(copy.review.status, copy.statuses.linked);
      await expect(items.first().getByLabel(copy.review.targetId, { exact: true })).toHaveValue(String(word.id));
      await items.first().getByRole("button", { name: copy.review.save, exact: true }).click();
      await expect(items).toHaveCount(0);
      await choose(copy.filters.status, copy.statuses.linked);
      await page.getByRole("button", { name: copy.filters.apply, exact: true }).click();
      await expect(items).toHaveCount(1);
      await items.first().getByRole("button", { name: copy.actions.inspect, exact: true }).click();
      await expect(items.first().getByRole("link", { name: copy.actions.openLinked, exact: true })).toHaveAttribute("href", new RegExp(encodeURIComponent(term)));
      await expect(page.getByText(copy.review.saved, { exact: true })).toBeHidden({ timeout: 7000 });
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({ path: testInfo.outputPath("search-gap-review.png"), fullPage: true, scale: "css", animations: "disabled" });
      await items.first().getByLabel(copy.review.targetId, { exact: true }).scrollIntoViewIfNeeded();
      await page.screenshot({ path: testInfo.outputPath("search-gap-review-viewport.png"), scale: "css", animations: "disabled" });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      expect(errors).toEqual([]);
    } finally {
      await sql`DELETE FROM search_gap_reviews WHERE query LIKE ${prefix + "%"}`;
      await cleanupSearchOutcomeEvents(sql, events);
      if (wordIds.length) await sql`DELETE FROM words WHERE id IN ${sql(wordIds)}`;
      if (actorId) await sql`DELETE FROM users WHERE id = ${actorId}`;
      await sql.end({ timeout: 5 });
    }
  });
}
